const fs=require('node:fs'), ts=require('typescript'), assert=require('node:assert/strict')
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename)
const {buildWalkCollision,canWalkAt,walkSpawn}=require('../lib/walk-collision.ts')
const box=(x1,y1,x2,y2)=>({x1,y1,x2,y2,width:x2-x1,height:y2-y1})
const item=(id,label,b)=>({id,label,box:b,class_id:1,confidence:1})
const wall=item('wall','wall',box(0,45,100,55))
const door=item('door','door',box(42,45,58,55))
const window=item('window','window',box(70,45,85,55))
const floor=item('floor','floor',box(0,0,100,100))
const detection=[wall,door,window,floor]
const collision=buildWalkCollision(detection,{width:100,height:100},.1,new Map([[wall.id,[door,window]]]))
assert.equal(collision.barriers.length,2,'door divides wall into two solid spans; window stays solid')
assert.equal(canWalkAt(0,0,collision),true,'door passage is open')
assert.equal(canWalkAt(-3,0,collision),false,'wall stops the player')
assert.equal(canWalkAt(2.6,0,collision),false,'window is not a doorway')
assert.equal(canWalkAt(6,0,collision),false,'camera stays on supported floor')
const sofa=item('sofa','furniture',box(15,15,38,25))
sofa.furnitureCatalogId='linen-sofa'
const furnished=buildWalkCollision([...detection,sofa],{width:100,height:100},.1,new Map([[wall.id,[door,window]]]))
assert.equal(canWalkAt(-2.4,-3,furnished),false,'sofa blocks the walkthrough')
const spawn=walkSpawn(detection,{width:100,height:100},.1,collision)
assert.equal(canWalkAt(spawn.x,spawn.z,collision),true)
console.log('PASS: walk spawn lies on floor; walls and windows block; door gap permits passage')
