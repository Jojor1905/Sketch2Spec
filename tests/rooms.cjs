const one=applyScopedMaterial(painted,'wall','wall-paint-white','selected','shared',null,'positive')
assert.equal(one.find(d=>d.id==='shared').wallFinishes.length,0)
const all=applyScopedMaterial(one,'wall','wall-paint-white','all',null,null,'positive')
assert.ok(all.filter(d=>d.label==='wall').every(d=>d.materialApplied&&d.wallFinishes.length===0))
assert.deepEqual(rebuildRoomFloors(painted,size),painted,'rebuild is idempotent and keeps stable room IDs and finishes')
const snapshot=cloneDetections(painted)
snapshot.find(d=>d.id===top.id).floorTiles[0].x1=0.001
assert.notDeepEqual(snapshot,painted)
