for(let i=0;i<rooms.length;i++) for(let j=i+1;j<rooms.length;j++) assert.equal(overlapArea(floorBoxes(rooms[i]),floorBoxes(rooms[j])),0)
assert.equal(rooms.reduce((a,r)=>a+floorAreaPx(r),0),17550)
const top=rooms.find(r=>r.box.x2<100&&r.box.y2<100), lower=rooms.find(r=>r.box.x2<100&&r.box.y1>100), right=rooms.find(r=>r.box.x1>100)
let painted=applyScopedMaterial(result,'floor','floor-oak','room',null,top.id,'positive')
assert.equal(painted.filter(d=>d.materialApplied).length,1)
painted=applyScopedMaterial(painted,'wall','wall-paint-white','room',null,top.id,'positive')
const shared=painted.find(d=>d.id==='shared')
assert.equal(shared.wallFinishes.length,1)
assert.equal(shared.wallFinishes[0].side,'negative')
assert.ok(shared.wallFinishes[0].end<0.5)
assert.equal(roomWallFaces(lower,shared)[0].side,'negative')
assert.equal(roomWallFaces(right,shared)[0].side,'positive')
painted=applyScopedMaterial(painted,'wall','wall-concrete','room',null,lower.id,'positive')
assert.equal(painted.find(d=>d.id==='shared').wallFinishes.length,2)
