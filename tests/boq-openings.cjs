const fs=require('node:fs'),ts=require('typescript'),assert=require('node:assert/strict')
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,filename)
const {calculateBudget}=require('../lib/materials.ts')
const box=(x1,y1,x2,y2)=>({x1,y1,x2,y2,width:x2-x1,height:y2-y1})
const item=(id,label,b,rest={})=>({id,label,box:b,class_id:1,confidence:1,...rest})
const wall=item('wall','wall',box(0,45,100,55),{materialId:'wall-paint-white',materialApplied:true,wallFinishes:[{side:'positive',start:0,end:.5,materialId:'scg-grit-honey'}]})
const door=item('door','door',box(10,45,20,55))
const window=item('window','window',box(40,45,60,55))
const detections=[wall,door,window]
const budget=calculateBudget(detections,{width:100,height:100},.1,'')
const scg=budget.lines.find(line=>line.materialId==='scg-grit-honey')
const base=budget.lines.find(line=>line.materialId==='wall-paint-white')
assert.ok(Math.abs(scg.quantity-10.7)<.01,scg)
assert.ok(Math.abs(base.quantity-36.3)<.01,base)
assert.equal(scg.packageQuantity,22,'packaging uses ceil(area / 0.5m² per box) without waste')
assert.equal(scg.unitPrice,null)
assert.equal(scg.total,null)
assert.equal(base.unitPrice,180)
assert.equal(budget.subtotal,Math.round(36.3*180))
const unscaled=calculateBudget(detections,{width:100,height:100},null,'')
assert.equal(unscaled.hasScale,false)
assert.deepEqual(unscaled.lines,[])
console.log('PASS: two wall faces subtract a door and window; face finish stays isolated; packaging rounds up without waste; scale gates BOQ')
