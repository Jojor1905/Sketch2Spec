const fs = require('node:fs')
const ts = require('typescript')
const assert = require('node:assert/strict')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, filename)

const { resizeWallThicknessAroundCenter, wallThicknessPx } = require('../lib/wall-thickness.ts')
const { openingsForWalls } = require('../lib/openings.ts')
const box = (x1, y1, x2, y2) => ({ x1, y1, x2, y2, width: x2 - x1, height: y2 - y1 })
const item = (id, label, shape) => ({ id, label, class_id: 1, confidence: 1, box: shape })
const image = { width: 800, height: 600 }
const horizontal = item('horizontal', 'wall', box(200, 180, 500, 200))
const vertical = item('vertical', 'wall', box(600, 100, 620, 400))
const door = item('door', 'door', box(270, 180, 310, 200))
const window = item('window', 'window', box(360, 180, 410, 200))

const before = openingsForWalls([horizontal, vertical, door, window], image)
assert.deepEqual(before.get(horizontal.id).map(opening => opening.id), ['door', 'window'])

const widened = resizeWallThicknessAroundCenter(horizontal.box, 40, image)
assert.equal(wallThicknessPx(widened), 40)
assert.equal((widened.y1 + widened.y2) / 2, 190)
assert.equal(widened.x1, horizontal.box.x1)
assert.equal(widened.x2, horizontal.box.x2)
const thickerVertical = resizeWallThicknessAroundCenter(vertical.box, 36, image)
assert.equal(wallThicknessPx(thickerVertical), 36)
assert.equal((thickerVertical.x1 + thickerVertical.x2) / 2, 610)
assert.equal(thickerVertical.y1, vertical.box.y1)
assert.equal(thickerVertical.y2, vertical.box.y2)

assert.equal(wallThicknessPx(resizeWallThicknessAroundCenter(horizontal.box, -100, image)), 4)
const capped = resizeWallThicknessAroundCenter(horizontal.box, 10000, image)
assert.equal(wallThicknessPx(capped), 210)
assert.ok(capped.width > capped.height, 'thickness cannot flip wall orientation')

const after = openingsForWalls([{ ...horizontal, box: widened }, vertical, door, window], image)
assert.deepEqual(after.get(horizontal.id).map(opening => opening.id), ['door', 'window'])
assert.equal(door.box.x1, 270)
assert.equal(window.box.x1, 360)
console.log('PASS: centered horizontal/vertical thickness, min/max limits, and door/window association')
